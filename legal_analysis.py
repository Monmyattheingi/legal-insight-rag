MYANMAR_DIGITS = str.maketrans("၀၁၂၃၄၅၆၇၈၉", "0123456789")


def _normalize(text):
    return unicodedata.normalize("NFC", str(text or "")).strip()


def _find_age(text):
    normalized = _normalize(text).translate(MYANMAR_DIGITS)
    patterns = (
        r"အသက်\s*(\d{1,3})\s*နှစ်",
        r"(\d{1,3})\s*နှစ်\s*အရွယ်",
    )
    for pattern in patterns:
        match = re.search(pattern, normalized)
        if match:
            age = int(match.group(1))
            if 0 <= age <= 120:
                return age
    return None


def _first_present(text, choices):
    return next((label for keyword, label in choices if keyword in text), None)


